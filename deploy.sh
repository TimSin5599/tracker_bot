#!/bin/bash

# Скрипт для ручного деплоя на сервере
# Используется как альтернатива или дополнение к CI/CD

set -e

echo "🚀 Начинаем деплой tracker_bot..."

# Переходим в директорию проекта
cd /opt/tracker_bot || exit 1

# Останавливаем текущие контейнеры
echo "⏹️  Останавливаем контейнеры..."
docker-compose down

# Получаем последние изменения (если используется git на сервере)
if [ -d ".git" ]; then
    echo "📥 Получаем последние изменения из репозитория..."
    git pull origin main
fi

# Собираем образы заново
echo "🔨 Собираем Docker образы..."
docker-compose build --no-cache

# Запускаем контейнеры
echo "▶️  Запускаем контейнеры..."
docker-compose up -d

# Ждем немного для инициализации
echo "⏳ Ждем инициализации сервисов..."
sleep 10

# Показываем статус
echo "📊 Статус контейнеров:"
docker-compose ps

# Показываем последние логи
echo "📋 Последние логи бота:"
docker-compose logs --tail=30 telegram-bot

echo "✅ Деплой завершен!"

